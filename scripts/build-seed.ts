// Generates supabase/seed.sql from lib/demo/seed.ts (the single source of seed data).
// Timestamps are written relative to now(), so "3 mix-ups in 7 days" works on any day.
// Run: pnpm db:seed:build

import { writeFileSync } from 'node:fs';
import { SEED, WAREHOUSE_NAME } from '../lib/demo/seed';
import { DEFAULT_SETTINGS } from '../lib/engine/constants';
import { GRADING_GUIDE } from '../lib/voice/agent-config';

const demoNowMs = new Date(SEED.demoNow).getTime();
const q = (v: string | null | undefined) => (v === null || v === undefined ? 'null' : `'${v.replace(/'/g, "''")}'`);
const n = (v: number | null | undefined) => (v === null || v === undefined ? 'null' : String(v));
const ts = (iso: string | null | undefined) => {
  if (!iso) return 'null';
  const secs = Math.round((demoNowMs - new Date(iso).getTime()) / 1000);
  return `now() - interval '${secs} seconds'`;
};
const arr = (xs: string[]) => (xs.length ? `array[${xs.map(q).join(',')}]::text[]` : `'{}'::text[]`);
const W = q(SEED.warehouseId);
const order = (id: string) => `(select id from public.orders where ext_id = ${q(id)})`;

const out: string[] = [];
out.push(`-- GENERATED by scripts/build-seed.ts from lib/demo/seed.ts. Do not edit by hand.
-- Resets all warehouse data to seed state. Profiles and auth users are kept.
begin;
select set_config('sjekkpunkt.allow_audit_purge', 'on', true);
truncate public.integration_events, public.audit_events, public.pack_alerts, public.confusion_events,
  public.escalations, public.stock_adjustments, public.decisions, public.inspections, public.return_items,
  public.returns, public.pack_scans, public.pack_checks, public.vision_results, public.photos, public.order_lines,
  public.orders, public.products, public.locations, public.settings;
select set_config('sjekkpunkt.allow_audit_purge', 'off', true);

insert into public.warehouses (id, name) values (${W}, ${q(WAREHOUSE_NAME)})
  on conflict (id) do update set name = excluded.name;
`);

out.push(`insert into public.devices (warehouse_id, label) values
${SEED.devices.map((d) => `  (${W}, ${q(d)})`).join(',\n')}
on conflict (label) do nothing;
`);

out.push(`insert into public.locations (warehouse_id, code, kind) values
${SEED.locations.map((l) => `  (${W}, ${q(l.code)}, ${q(l.kind)})`).join(',\n')};
`);

out.push(`insert into public.products (warehouse_id, sku, name_nb, name_en, category, color, size, price_nok, location_code, variant_group, barcode) values
${SEED.products
  .map((p) => `  (${W}, ${q(p.sku)}, ${q(p.nameNb)}, ${q(p.nameEn)}, ${q(p.category)}, ${q(p.color)}, ${q(p.size)}, ${p.priceNok}, ${q(p.location)}, ${q(p.variantGroup)}, ${q(p.barcode)})`)
  .join(',\n')};
`);

out.push(`insert into public.orders (warehouse_id, ext_id, customer_ref, status, shipped_at) values
${SEED.orders.map((o) => `  (${W}, ${q(o.id)}, ${q(o.customerRef)}, ${q(o.status)}, ${ts(o.shippedAt)})`).join(',\n')};

insert into public.order_lines (warehouse_id, order_id, sku, qty, price_nok) values
${SEED.orders.flatMap((o) => o.lines.map((l) => `  (${W}, ${order(o.id)}, ${q(l.sku)}, ${l.qty}, ${l.priceNok})`)).join(',\n')};
`);

out.push(`insert into public.pack_checks (warehouse_id, order_id, status, method, size_verified, confidence, photo_ref, device_id, engine_version, created_at) values
${[...SEED.packChecks, ...SEED.nearMisses]
  .map((c) => `  (${W}, ${order(c.orderId)}, ${q(c.status)}, ${q(c.method ?? 'camera')}, ${c.sizeVerified}, ${c.confidence.toFixed(3)}, ${q(c.photoRef)}, (select id from public.devices where label = ${q(c.deviceId)}), 'seed', ${ts(c.at)})`)
  .join(',\n')};
`);

out.push(`insert into public.returns (warehouse_id, ext_id, order_id, customer_reason_nb, registered_at, status) values
${SEED.returns.map((r) => `  (${W}, ${q(r.id)}, ${order(r.orderId)}, ${q(r.customerReasonNb)}, ${ts(r.registeredAt)}, ${q(r.status)})`).join(',\n')};
`);

out.push(`insert into public.return_items (warehouse_id, return_id, item_index, ordered_sku, received_sku, qty, status) values
${SEED.returns
  .flatMap((r) =>
    r.items.map((it, i) => {
      const d = SEED.pastDecisions.find((x) => x.returnId === r.id && x.itemIndex === i);
      return `  (${W}, (select id from public.returns where ext_id = ${q(r.id)}), ${i}, ${q(it.orderedSku)}, ${q(d?.receivedSku)}, ${it.qty}, ${q(d ? 'decided' : 'pending')})`;
    }),
  )
  .join(',\n')};
`);

out.push(`insert into public.decisions (warehouse_id, return_item_id, grade, location_code, refund_nok, cause, flags, engine_version, decided_at) values
${SEED.pastDecisions
  .map((d) => `  (${W}, (select ri.id from public.return_items ri join public.returns r on r.id = ri.return_id where r.ext_id = ${q(d.returnId)} and ri.item_index = ${d.itemIndex}), ${q(d.grade)}, ${q(d.locationCode)}, ${n(d.refundNok)}, ${q(d.cause)}, ${arr(d.flags)}, 'seed', ${ts(d.decidedAt)})`)
  .join(',\n')};
`);

out.push(`insert into public.confusion_events (warehouse_id, sku_a, sku_b, kind, source_type, at) values
${SEED.confusionEvents
  .map((e) => {
    const [a, b] = [...e.skuPair].sort();
    return `  (${W}, ${q(a)}, ${q(b)}, ${q(e.kind)}, 'seed', ${ts(e.at)})`;
  })
  .join(',\n')};
`);

out.push(`insert into public.integration_events (warehouse_id, type, payload, created_at) values
${SEED.integrationEvents.map((e) => `  (${W}, ${q(e.type)}, ${q(JSON.stringify(e.payload))}::jsonb, ${ts(e.at)})`).join(',\n')};
`);

const settings: Record<string, unknown> = {
  pack_confidence_min: DEFAULT_SETTINGS.packConfidenceMin,
  return_confidence_min: DEFAULT_SETTINGS.returnConfidenceMin,
  confusion_threshold: DEFAULT_SETTINGS.confusionThreshold,
  confusion_window_days: DEFAULT_SETTINGS.confusionWindowDays,
  max_retakes: DEFAULT_SETTINGS.maxRetakes,
  return_window_days: DEFAULT_SETTINGS.returnWindowDays,
  photo_retention_days: 30,
  wrong_parcel_cost_nok: 340,
  enabled_languages: ['nb', 'en', 'pl', 'uk', 'ro', 'lt'],
  daily_spend_cap_nok: { vision: 200, elevenlabs: 300 },
  grading_guide: GRADING_GUIDE,
};
out.push(`insert into public.settings (warehouse_id, key, value) values
${Object.entries(settings)
  .map(([k, v]) => `  (${W}, ${q(k)}, ${q(JSON.stringify(v))}::jsonb)`)
  .join(',\n')};
`);

out.push(`insert into public.audit_events (warehouse_id, station, type, summary_nb, summary_en) values
  (${W}, 'system', 'SEED_LOADED', 'Demodata lastet inn', 'Seed data loaded');

commit;
`);

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), out.join('\n'));
console.log(`seed.sql: ${SEED.products.length} products, ${SEED.orders.length} orders, ${SEED.returns.length} returns, ${SEED.pastDecisions.length} past decisions, ${SEED.confusionEvents.length} confusion events, ${SEED.nearMisses.length} near-misses, ${SEED.integrationEvents.length} integration events`);
