// Design tokens: design/tokens.json (copied from the Sjekkpunkt design system) is the source.
// `pnpm design:tokens` writes app/tokens.css from it; lib/design/tokens.test.ts fails when the two
// drift. Pure: no file access here, so the script and the test share it.

export interface Token {
  name: string;
  value: string;
  usage?: string;
}
export interface TypeStyle {
  name: string;
  fontSize: string;
  lineHeight: string;
  fontWeight: number;
  letterSpacing?: string;
}
export interface DesignTokens {
  color: { tokens: Token[] };
  type: { families: { sans: string; mono: string }; groups: { name: string; family: 'sans' | 'mono'; styles: TypeStyle[] }[] };
  spacing: { tokens: Token[] };
  radius: { tokens: Token[] };
  shadow: { tokens: Token[] };
  size: { tokens: Token[] };
  feature: { tokens: Token[] };
  duration: { tokens: Token[] };
  easing: { tokens: Token[] };
}

/** The CSS variables next/font sets in app/layout.tsx; they go in front of the token families. */
export const FONT_VARIABLES = { sans: '--font-golos-text', mono: '--font-jetbrains-mono' } as const;

/** `{ink}` (an alias in tokens.json) becomes `var(--ink)`. */
const ref = (value: string) => value.replace(/^\{([a-z0-9-]+)\}$/, 'var(--$1)');

/** Resolves an alias chain to a literal hex value (for contrast checks). */
export function resolveColor(tokens: DesignTokens, name: string): string {
  const byName = new Map(tokens.color.tokens.map((t) => [t.name, t.value]));
  let v = byName.get(name);
  for (let i = 0; v && v.startsWith('{') && i < 5; i++) v = byName.get(v.slice(1, -1));
  if (!v) throw new Error(`unknown colour token: ${name}`);
  return v;
}

export function buildTokensCss(t: DesignTokens): string {
  const out: string[] = [
    '/* Generated by `pnpm design:tokens` from design/tokens.json (the Sjekkpunkt design system). Do not edit. */',
    '',
    ':root {',
  ];
  const section = (title: string, tokens: Token[]) => {
    out.push(`  /* ${title} */`);
    for (const tk of tokens) out.push(`  --${tk.name}: ${ref(tk.value)};`);
  };
  section('colour', t.color.tokens);
  section('spacing', t.spacing.tokens);
  section('size', t.size.tokens);
  section('feature', t.feature.tokens);
  section('duration', t.duration.tokens);
  out.push('  /* type families: the next/font family first, then the stack from tokens.json */');
  out.push(`  --font-family-sans: var(${FONT_VARIABLES.sans}), ${t.type.families.sans};`);
  out.push(`  --font-family-mono: var(${FONT_VARIABLES.mono}), ${t.type.families.mono};`);
  out.push('}', '');

  // Radius, shadow and easing tokens already carry Tailwind's theme names (radius-md, shadow-raised,
  // ease-out), so they are theme variables themselves: rounded-md, shadow-raised and ease-out use
  // them, and so does app/ui.css through var(--radius-md). Static: always emitted.
  out.push('@theme static {');
  for (const tk of [...t.radius.tokens, ...t.shadow.tokens, ...t.easing.tokens]) out.push(`  --${tk.name}: ${ref(tk.value)};`);
  out.push('}', '');

  // Aliases for the rest: bg-surface, text-ink-2, border-stop, min-h-target-handheld, font-mono.
  // Tailwind's numeric spacing (p-4 = 16px) is the token scale (space-N = N × 4px), checked by the test.
  out.push('@theme inline {');
  for (const tk of t.color.tokens) out.push(`  --color-${tk.name}: var(--${tk.name});`);
  for (const tk of t.size.tokens) if (!tk.name.startsWith('text-')) out.push(`  --spacing-${tk.name}: var(--${tk.name});`);
  out.push('  --font-sans: var(--font-family-sans);');
  out.push('  --font-mono: var(--font-family-mono);');
  out.push('}', '');

  // Type styles as utilities (type-verdict, type-shelf, …): family, size, line height, weight,
  // tracking in one class. Code styles also get tabular figures.
  for (const g of t.type.groups) {
    for (const s of g.styles) {
      out.push(`@utility type-${s.name} {`);
      out.push(`  font-family: var(--font-family-${g.family});`);
      out.push(`  font-size: ${s.fontSize};`);
      out.push(`  line-height: ${s.lineHeight};`);
      out.push(`  font-weight: ${s.fontWeight};`);
      if (s.letterSpacing) out.push(`  letter-spacing: ${s.letterSpacing};`);
      if (g.family === 'mono') out.push('  font-variant-numeric: var(--numeric);');
      out.push('}');
    }
  }
  for (const tk of t.duration.tokens) {
    out.push(`@utility ${tk.name} {`, `  transition-duration: var(--${tk.name});`, '}');
  }
  out.push('');
  return out.join('\n');
}

// ---------- contrast (WCAG 2.x) ----------

const channel = (c: number) => {
  const s = c / 255;
  return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
};
const luminance = (hex: string) => {
  const h = hex.replace('#', '');
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16));
  return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b);
};
export function contrast(a: string, b: string): number {
  const [x, y] = [luminance(a), luminance(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
}
